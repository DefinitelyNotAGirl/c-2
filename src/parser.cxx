/**
 * @brief
 * 
 * @callgraph
 * @callergraph
 * 
 * @param name 
 * @param args 
 * @return std::string 
 */
std::string getFunctionExpression(std::string name,
								  std::vector<variable*>& args) {
	std::string res = name + "(";
	for (variable* i : args)
	{
		if(i == nullptr)
		{
			//,
			//, dump compiler state
			//,
			{
				errorCompilerBug;
				//sdump(currentScope);
				sdump(i);
				sdump(&name);
				printStacktrace(50);
			}
			continue;
		}
		if(i->dataType == nullptr)
		{
			std::cout << "variable " << name << " has no data type" << std::endl;
			continue;
		}
		res += i->dataType->name + ",";
	}
	if (res.back() == ',') 
		res.pop_back();
	res += ")";
	return res;
}

